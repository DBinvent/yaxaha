#!/usr/bin/env bash
# [§8] Concurrent document modification: N nodes patching ONE jsonb row at once.
#
# This is the case the product claims and the one a unit test cannot reach. The
# claim is that two writers touching DISJOINT paths of the same document both
# survive - `base + patch_A + patch_B == base + patch_B + patch_A` - and the
# only way to believe it is to have real nodes race on a real replicated row.
#
# ## What the first run of this script found (2026-09-24)
#
# It failed, and for the right reason. `ClusterCommitMerge` was declared in
# `cluster.proto`, surfaced by `yt_info('a:<table>')`, and **read by nothing** -
# so the replicated apply was the ordinary whole-column compare-and-set:
#
#     update t set doc = <origin's whole document> where pk and doc = <origin's old>
#
# Two nodes patching keys that have nothing in common still fail each other's
# precondition; the later one matches 0 rows, logs `[cas-miss]`, and **commits
# anyway**. Seven nodes, seven keys, and each node kept two or three of them.
#
# The fix is per-path: the patch and the precondition both became the PATH
# rather than the whole value (`ytserv/src/ycluster/merge.rs`, design in
# `ytserv/merge.md`). Disjoint paths then commute, which is what section 2 here
# measures, and intersecting ones are REFUSED rather than silently dropped,
# which is section 3.
#
# Worth keeping in view: this script was written, committed, and **structurally
# incapable of running** - its shared `wait_writable` helper probed the `jsonb`
# column with a non-JSON literal, so all 24 attempts errored before any
# assertion and the whole thing was recorded as "written but never run". The
# bug it was written to catch was real and sat undetected behind a test that
# could not execute.
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"
echo "== jsonb merge: concurrent disjoint patches all survive =="

# merge on, `cluster_commit` left at the cluster default (`half`).
#
# Generated by `yxctl --encode-table-cfg`, not hand-computed. It could not be at
# first: `parse_spec` had no `merge` key and `encode()` dropped the field, so the
# only way to turn merge on was a base64 constant worked out from a Rust test.
# Both ends are wired now (and `cluster_commit`, `filter` and `db_source` with
# them - all three were accepted on the command line and silently discarded).
#
# `half` and not `ALL`, though ALL would make section 3 tidier. Under ALL every
# node is in every party, so the party's own row locks serialise two writers on
# one row - the second reads the first's value and the intersection never
# happens. That is a better outcome than detecting it, but it would mean
# section 3 tested the row lock rather than the conflict path, and it puts
# seven concurrent section-2 writers into a seven-way distributed lock cycle
# with no deadlock detector across nodes. `half` is also what a real table runs.
MERGE_CFG="$("$REPO_ROOT"/target/release/yxctl --encode-table-cfg 'merge' | tail -1)"

for n in "${NODES[@]}"; do
	q "$n" "drop table if exists jm_t; create table jm_t (id int primary key, doc jsonb);" >/dev/null
done
# No az rule: every node holds the row, so every node is a writer to the same
# one. That is the point - scoping it would remove the contention being tested.
register_table public.jm_t "$MERGE_CFG"
restart_all
await_cluster
wait_writable n1 n2 jm_t || { bad "cluster never became writable"; summary; }

# ## Wait for the apply path, and do NOT count while it is behind
#
# `wal_gap` is the number of subterms a node is still missing. While it is
# non-zero, writes to synced tables "wait and retry until they close"
# (`recon.rs`), and a key that has not arrived yet is indistinguishable from one
# a merge dropped. Counting through that is how the first in-suite run of this
# script reported `n1 is MISSING committed writes: n3 - a merge dropped them`
# when n1's log carried no `[cas-miss]` at all and its gap closed on its own a
# minute later. Run alone, on a fresh cluster, the same script was 24/24.
#
# So the gap is a PRECONDITION, checked before the writes and again before the
# count - and when it will not close, the test says "replication gap", because
# that is what it is.
# `-1` for "this node has not reported yet", NOT 0. health.metrics does not
# exist until the health monitor's first tick, and a restart is exactly when it
# has not ticked - so defaulting the absence to 0 made wait_gaps_closed return
# success immediately after `restart_all`, reporting every node caught up when
# it had simply not been told. Same silent-pass shape as globbing a message for
# a SQLSTATE: an absent answer read as a good one.
gap_of() { # gap_of <node> -> subterms still missing, or -1 if unknown
	local m g
	m="$(info "$1" E health.metrics)"
	if [ -z "$m" ]; then printf '%s' "-1"; return; fi
	g="$(printf '%s' "$m" | sed -n 's/.*wal_gap \([0-9][0-9]*\).*/\1/p')"
	if [ -z "$g" ]; then printf '%s' "-1"; else printf '%s' "$g"; fi
}
# The worst thing any node is reporting: a real gap beats "unknown" beats 0, so
# one silent node cannot be averaged away by six healthy ones.
worst_gap() {
	local n g worst=0 unknown=0
	for n in "${NODES[@]}"; do
		g="$(gap_of "$n")"
		if [ "$g" = "-1" ]; then unknown=1
		elif [ "$g" -gt "$worst" ]; then worst="$g"; fi
	done
	if [ "$worst" -eq 0 ] && [ "$unknown" -eq 1 ]; then printf '%s' "-1"
	else printf '%s' "$worst"; fi
}
wait_gaps_closed() { # bounded; 0 = every node reported, and all caught up
	local i w
	for i in $(seq 1 "${1:-24}"); do
		w="$(worst_gap)"
		if [ "$w" = "0" ]; then return 0; fi
		sleep 5
	done
	return 1
}

if wait_gaps_closed 24; then
	ok "every node's apply path is caught up before the test writes"
else
	w="$(worst_gap)"
	if [ "$w" = "-1" ]; then
		bad "after 120s at least one node has not reported health.metrics at all, so \
the apply path's state is UNKNOWN - anything measured below is measured blind"
	else
		bad "the cluster still has $w subterm gap(s) after 120s - writes to synced \
tables wait on those, so anything measured below is measuring the gap"
	fi
fi

# ── 0. merge is actually ON ──────────────────────────────────────────────────
#
# In band, before anything else, because every assertion below would ALSO pass
# on a lucky arrival order - and a test that can pass with the feature switched
# off is the exact failure this whole exercise exists to remove. `-` is the
# value yt_info prints for a table with no merge config.
for n in "${NODES[@]}"; do
	mg="$(info "$n" "a:public.jm_t" merge)"
	case "$mg" in
		-|"") bad "$n has merge OFF for jm_t (yt_info says [${mg:-<absent>}]) - \
the module-A value did not load; a restart is required after writing it" ;;
		*) [ "$n" = "n1" ] && ok "merge is on for jm_t: $mg" ;;
	esac
done

q n1 "insert into jm_t (id, doc) values (1, '{}'::jsonb);" >/dev/null
sleep 2

# ── 1. the primitive, before trusting it under load ──────────────────────────
#
# ytpgc/test.sql already asserts commutativity for disjoint paths; repeat the
# barest form here so that a failure below can be attributed. If this fails the
# extension is wrong and the concurrency result means nothing.
echo "  checking yt_diff_apply/yt_diff_encode are present and commutative..."
both=$(q n1 "select yt_diff_apply(
                 yt_diff_apply('{}'::jsonb,
                   yt_diff_encode('{\"doc\":{\"hunks\":[{\"path\":[{\"name\":\"a\"}],\"value\":{\"update\":{\"string\":\"1\"}}}]}}'::jsonb)),
                 yt_diff_encode('{\"doc\":{\"hunks\":[{\"path\":[{\"name\":\"b\"}],\"value\":{\"update\":{\"string\":\"2\"}}}]}}'::jsonb))
             = '{\"a\":\"1\",\"b\":\"2\"}'::jsonb;" 2>&1 | tr -d ' ')
check "a then b yields both keys" "$both" "t"

rev=$(q n1 "select yt_diff_apply(
                 yt_diff_apply('{}'::jsonb,
                   yt_diff_encode('{\"doc\":{\"hunks\":[{\"path\":[{\"name\":\"b\"}],\"value\":{\"update\":{\"string\":\"2\"}}}]}}'::jsonb)),
                 yt_diff_encode('{\"doc\":{\"hunks\":[{\"path\":[{\"name\":\"a\"}],\"value\":{\"update\":{\"string\":\"1\"}}}]}}'::jsonb))
             = '{\"a\":\"1\",\"b\":\"2\"}'::jsonb;" 2>&1 | tr -d ' ')
check "b then a yields the same document" "$rev" "t"

# `update` on an absent key must CREATE it - the C routes update and insert
# both to map_set (insert-or-replace), and a node writing its own key for the
# first time depends on that.
crt=$(q n1 "select yt_diff_apply('{\"x\":1}'::jsonb,
               yt_diff_encode('{\"doc\":{\"hunks\":[{\"path\":[{\"name\":\"new\"}],\"value\":{\"update\":{\"boolean\":true}}}]}}'::jsonb))
             = '{\"x\":1,\"new\":true}'::jsonb;" 2>&1 | tr -d ' ')
check "update on an absent key creates it" "$crt" "t"

# ── 2. the real case: every node patches its own key simultaneously ──────────
#
# A PLAIN `doc || '{...}'`, deliberately, where this used to call yt_diff_apply
# in the client's own statement. The client-side form only ever proved the
# extension's primitive works locally; what diverged was the REPLICATION of the
# resulting row, and the merge being tested is the one ytserv computes from the
# trigger's old/new images. An application writes jsonb the ordinary way, so
# that is what the test writes.
# ## Every writer's outcome is CAPTURED, not discarded
#
# This used to send all the writes to /dev/null and then count keys, so a missing
# key could mean either "the merge lost it" - the bug - or "the cluster refused
# that write" - contention, a different thing entirely. Every writer's outcome is
# captured now, and a refused one is reported and excluded, so the assertion is
# the one that means something: EVERY WRITE THAT COMMITTED IS PRESENT ON EVERY
# NODE THAT IS CAUGHT UP.
#
# ## How many writers at once, and why it is not the whole roster
#
# It was, and the whole roster is more contention than this cluster sustains:
# four runs of one binary committed 1, 3, 4 and 6 of 7. Each write holds the row
# on its party for the length of its own 2PC, and `def_sql_timeout_sec` is 1s,
# so the losers time out - and a timed-out write has already taken a subterm at
# checkin, leaving a hole every node behind it waits on. The result was a test
# whose subject was decided by how many writers happened to lose that race.
#
# What merge actually claims is that patches from writers who read the SAME base
# commute. That needs SIMULTANEITY, not maximum contention - and it is not
# weakened by using fewer writers: with the whole-column CAS, three disjoint
# simultaneous patches still lose at least one, so this catches the original bug
# exactly as the seven-way version did. Staggering them would NOT: a writer that
# reads a base already containing the others' keys has no conflicting
# precondition, and the old CAS would pass it too.
#
# Raise YX_MERGE_WRITERS to run the contention case deliberately; it is a
# different question and this is not the script that answers it. (The timeouts
# above are gone since [wait-die]: the younger writer of a row is refused with
# 40001 at once and retries - YX_MERGE_RETRIES, default 20.)
writers=( "${NODES[@]:0:${YX_MERGE_WRITERS:-3}}" )
echo "  ${#writers[@]} nodes patching one row at the same instant..."
# Read the SQLSTATE from its own FIELD. A glob over the message text cannot tell
# the field a driver acts on from prose a human reads - that mistake is what let
# an earlier assertion in 85_alert.sh report "SQLSTATE 55000, not 08006" while
# the real code was still 08006 and the digits sat in the message.
# `|| true`: no ERROR line is the SUCCESS case here, and grep reports "no match"
# as exit 1 - which under this file's `set -euo pipefail` killed the script at
# the first committed writer, silently, with no assertion having run.
sqlstate_of() {
	printf '%s\n' "$1" | { grep -m1 '^ERROR:' || true; } \
		| sed -n 's/^ERROR:  \([0-9A-Z]\{5\}\):.*/\1/p'
}

# Each writer retries on 40001, as a driver does: a younger writer of the row is
# refused at once rather than queued behind the older one ([wait-die]), and its
# re-run lands after it. Nothing else is retried.
outs=(); pids=()
for n in "${writers[@]}"; do
	o="$(mktemp)"; outs+=("$o")
	(
		a=0
		while :; do
			a=$((a + 1))
			printf '%s\n' "begin;
			    update jm_t set doc = coalesce(doc,'{}'::jsonb)
			        || jsonb_build_object('$n', jsonb_build_object('node','$n','seq',1))
			    where id = 1;
			    select yt_complete(true); commit;" \
			| rh "docker exec -i -u postgres -e PGOPTIONS='-c lock_timeout=30s' $n \
				psql -v VERBOSITY=verbose -d $YX_DB 2>&1" > "$o" 2>&1 || true
			{ [ "$(sqlstate_of "$(cat "$o")")" = "40001" ] && [ "$a" -lt "${YX_MERGE_RETRIES:-20}" ]; } || break
			sleep "0.$(( RANDOM % 4 + 1 ))"
		done
		echo "$a" > "$o.tries"
	) &
	pids+=($!)
done
for p in "${pids[@]}"; do wait "$p"; done
sleep 5

won=(); lost=(); why=""; retried=0
for i in "${!writers[@]}"; do
	o="$(cat "${outs[$i]}")"
	c="$(sqlstate_of "$o")"
	retried=$(( retried + $(cat "${outs[$i]}.tries" 2>/dev/null || echo 1) - 1 ))
	rm -f "${outs[$i]}.tries"
	if [ -z "$c" ]; then
		won+=("${writers[$i]}")
	else
		lost+=("${writers[$i]}:$c")
		# keep one verbatim, so "refused" is attributable rather than a code
		[ -n "$why" ] || why="$(printf '%s' "$o" | { grep -m1 '^ERROR:' || true; })"
	fi
	rm -f "${outs[$i]}"
done
echo "    committed: ${won[*]:-none}"
if [ ${#lost[@]} -gt 0 ]; then
	echo "    refused:   ${lost[*]}"
	echo "               $why"
	# Any refusal left after the retries fails below; a MERGE conflict is named
	# here - these writers patch disjoint paths, so 55409 would mean the diff or
	# the precondition is addressing the wrong place in the document.
	#
	# Tested against the PARSED codes, not by globbing "$why" for 55409. The
	# message text of a timeout can name a code for reasons of its own, and
	# "grep the message" is the exact mistake this suite has already made once.
	conflicted=""
	for e in "${lost[@]}"; do
		if [ "${e##*:}" = "55409" ]; then conflicted="$conflicted ${e%%:*}"; fi
	done
	[ -z "$conflicted" ] \
		|| bad "DISJOINT writer(s)$conflicted were refused as intersecting - the \
per-path precondition is matching a path the patch does not touch"
fi

# ## Assert over the nodes that are CAUGHT UP, and observe the rest
#
# A write that is refused still took a subterm from the leader at checkin, and
# that subterm is never applied anywhere - so it is a permanent hole, and every
# node behind it waits on a record that is not coming. Seven writers contending
# for one row produce several. That is a real property of the cluster and a
# pre-existing one; it is not what this script is about, and asserting through
# it makes the result a coin flip - two runs of this same binary gave 24/24 and
# 16/9 purely on how many writers happened to time out.
#
# So the split. For a node with NO gap, the statement is exact and cannot be
# explained away: it has received everything that was sent, so a committed
# writer's key is either there or a merge dropped it. Nodes still behind are
# REPORTED, with their gap, and excluded - not quietly, and not as a pass.
wait_gaps_closed 24 || true
settled=(); behind=()
for n in "${NODES[@]}"; do
	g="$(gap_of "$n")"
	if [ "$g" = "0" ]; then settled+=("$n"); else behind+=("$n:$g"); fi
done
echo "    settled:   ${settled[*]:-none}"
if [ ${#behind[@]} -gt 0 ]; then
	echo "    behind:    ${behind[*]}  (subterm holes left by the refused writers;"
	echo "               pre-existing same-row contention, not a merge result)"
fi

# EVERY writer commits. Before [wait-die] this was reported, not asserted: two
# writers of one row deadlocked across nodes (each origin kept its own row lock
# through the 2PC, the other's party session queued behind it) and died of
# def_sql_timeout_sec - 0 of 3 committed in four runs of six, 1 of 3 in the other
# two. Now the younger is refused with 40001 at once and its retry commits.
[ "${#won[@]}" -eq "${#writers[@]}" ] \
	&& ok "all ${#writers[@]} concurrent writers committed ($retried retr$([ "$retried" = 1 ] && echo y || echo ies) on 40001)" \
	|| bad "only ${#won[@]} of ${#writers[@]} concurrent writers committed - refused: ${lost[*]}"
[ "${#settled[@]}" -ge 2 ] \
	&& ok "${#settled[@]} of ${#NODES[@]} nodes caught up - enough to compare" \
	|| bad "only ${#settled[@]} node(s) caught up - nothing below is a real comparison"

# THE assertion: on a node with no gap, every committed writer's key is present.
# Before the merge existed this was 2-3 of 7 - each node kept whichever patches
# happened to arrive in an order its whole-column CAS accepted, and the rest were
# dropped with a warning and committed anyway.
for n in "${settled[@]}"; do
	missing=""
	for w in "${won[@]}"; do
		[ "$(q "$n" "select doc ? '$w' from jm_t where id=1")" = "t" ] || missing="$missing $w"
	done
	[ -z "$missing" ] \
		&& ok "$n (no gap) holds every committed writer's key (${#won[@]})" \
		|| bad "$n has NO replication gap and is still missing$missing - a merge \
dropped them"
done

# And the documents must be identical across the caught-up nodes - a merge that
# produced a different result on each would satisfy the count above and still be
# divergence.
for n in "${settled[@]:1}"; do
	check_same "${settled[0]} and $n hold the identical merged document" "${settled[0]}" "$n" \
		"select md5(doc::text) from jm_t where id = 1" 1 jm_t
done

# ── 3. the overlap case: REFUSED, deterministically ─────────────────────────
#
# Disjoint paths commute; the SAME path does not. This used to document that as
# an unspecified boundary - "no guarantee", asserting only that the cluster
# agreed which writer won. It now has a right answer (merge.md 5.1): an overlap
# is outside the guarantee, so it is REFUSED rather than resolved, and the
# refusal reaches the client as a SQLSTATE it can act on.
#
# ## Why this is staged rather than raced
#
# The obvious test - two nodes writing the same key at the same instant - is a
# coin flip here, and not a fixable one. The conflict needs both writers to read
# the same base, so the window is from the first UPDATE until its fan-out
# commits: tens of milliseconds. Widening it means holding a transaction open,
# and a party peer blocked on that row lock then exceeds `def_sql_timeout_sec`
# (1s) and the write dies of a timeout instead - which is what the first
# attempt at this section did, six times out of six. The timeout is not this
# test's to change.
#
# So the divergence is created OUT OF BAND, the way 85_alert.sh creates its
# split: one node's copy of the contended path is changed with the trigger off,
# which is indistinguishable, to the merge path, from a concurrent writer whose
# patch got there first. Then ONE ordinary merge write runs against it. No race,
# no held transaction, no timeout - and the conflict is certain.
#
# `cluster_commit = ALL` for THIS table, so the diverged node is certainly in
# the party. Under `half` the party is a subset and the conflict might simply
# not be looked at, which would make the assertion depend on which nodes were
# drawn. One writer, so ALL costs nothing in contention here.
echo "  an intersecting write must be refused, not merged..."
MERGE_ALL_CFG="$("$REPO_ROOT"/target/release/yxctl --encode-table-cfg 'merge; cluster_commit=all' | tail -1)"
for n in "${NODES[@]}"; do
	q "$n" "drop table if exists jm_x; create table jm_x (id int primary key, doc jsonb);" >/dev/null
done
register_table public.jm_x "$MERGE_ALL_CFG"
restart_all
await_cluster
wait_writable n1 n2 jm_x || { bad "cluster never became writable for jm_x"; summary; }

q n1 "begin; insert into jm_x (id, doc) values (1, '{\"k\":\"base\",\"other\":0}'::jsonb);
      select yt_complete(true); commit;" >/dev/null
sleep 3
for n in "${NODES[@]}"; do
	[ "$(q "$n" "select doc->>'k' from jm_x where id=1")" = "base" ] ||
		bad "the seed did not reach $n - every assertion below would be vacuous"
done

# n4's copy of `k` moves out from under any patch that expects "base".
trg="$(q n4 "select tgname from pg_trigger where tgrelid='jm_x'::regclass and not tgisinternal and (tgtype & 1) = 1 limit 1")"
q n4 "alter table jm_x disable trigger $trg;
      update jm_x set doc = doc || '{\"k\":\"elsewhere\"}'::jsonb where id=1;
      alter table jm_x enable trigger $trg;" >/dev/null
check "n4 holds a divergent value at the contended path" "elsewhere" \
	"$(q n4 "select doc->>'k' from jm_x where id=1")"

# (a) A write to a DIFFERENT path must still succeed. The divergence is at `k`;
# `other` has nothing to do with it, and a merge that refused this would have
# thrown away the commutativity it exists to provide.
out_ok="$(printf '%s\n' \
	"begin; update jm_x set doc = doc || '{\"other\":1}'::jsonb where id=1; \
	 select yt_complete(true); commit;" \
	| rh "docker exec -i -u postgres -e PGOPTIONS='-c lock_timeout=30s' n1 \
		psql -v VERBOSITY=verbose -d $YX_DB 2>&1")"
code_ok="$(sqlstate_of "$out_ok")"
[ -z "$code_ok" ] \
	&& ok "a disjoint path still commits over a divergent row" \
	|| bad "a DISJOINT write was refused with $code_ok - merge lost its whole point: \
$(printf '%s' "$out_ok" | grep -m1 ERROR)"
sleep 3

# ── THE merge property, proven without a race ───────────────────────────────
#
# This is the assertion the whole change exists for, and it needs no concurrency
# at all - which is why it, and not the seven-way write above, is the guarantee.
#
# n4 holds `{"k":"elsewhere","other":0}`; n1 patched `other` from 0 to 1 against
# a base where `k` was still "base". The patch says "set other, which is
# currently 0", and that is true on n4 - so n4 must end up holding BOTH its own
# divergent `k` AND n1's `other`. The patch composed with a value its origin
# never saw, which is exactly what "disjoint paths commute" means.
#
# Under the whole-column CAS this replaced, n1's statement was
#   set doc = '{"k":"base","other":1}' where doc = '{"k":"base","other":0}'
# which matches ZERO rows on n4: the write is dropped, n4 keeps other=0, and the
# two nodes stay divergent with no error anywhere. So this one assertion fails
# on the old behaviour and passes on the new one, deterministically, every run.
n4k="$(q n4 "select doc->>'k' from jm_x where id=1")"
n4o="$(q n4 "select doc->>'other' from jm_x where id=1")"
check "the diverged node KEPT its own value at the untouched path" "elsewhere" "$n4k"
check "...and still RECEIVED the patch to the disjoint path" "1" "$n4o"
[ "$n4k" = "elsewhere" ] && [ "$n4o" = "1" ] \
	&& ok "the patch composed with a value its origin never saw - paths commute" \
	|| bad "n4 holds k=$n4k other=$n4o - the patch did not compose; this is the \
whole-column CAS behaviour, i.e. merge is not running on this table"

# (b) A write to the CONTENDED path must be refused.
out_no="$(printf '%s\n' \
	"begin; update jm_x set doc = doc || '{\"k\":\"n1\"}'::jsonb where id=1; \
	 select yt_complete(true); commit;" \
	| rh "docker exec -i -u postgres -e PGOPTIONS='-c lock_timeout=30s' n1 \
		psql -v VERBOSITY=verbose -d $YX_DB 2>&1")"
code_no="$(sqlstate_of "$out_no")"
echo "    intersecting write -> [${code_no:-committed}]"

# 55409 and not 40409 is the one thing here that is easy to get backwards. Class
# 40 is transaction rollback, and it is what every driver in the stack retries
# automatically. A retry re-reads, re-applies on top of the other writer's value
# and discards the intent of one of the two edits - the one action that cannot
# converge. Class 55 (object_not_in_prerequisite_state) says the row is not in
# the state the write assumed and repeating will not change that, so it surfaces
# to whoever can actually decide.
case "$code_no" in
	55409) ok "the intersecting write is refused with 55409 - do not retry, needs review" ;;
	40409) bad "refused with 40409: class 40 tells every driver to RETRY, and a retry \
cannot converge an intersecting write (merge.md 5.1)" ;;
	08006) bad "refused with the generic 08006 - ytserv did not prefix a SQLSTATE, or a \
wrapper buried the prefix behind a label again: $(printf '%s' "$out_no" | grep -m1 ERROR)" ;;
	"")    bad "the intersecting write COMMITTED - it was silently merged over a value \
it never saw, which is the divergence this exists to stop" ;;
	*)     bad "refused with SQLSTATE $code_no, expected 55409: $(printf '%s' "$out_no" | grep -m1 ERROR)" ;;
esac

# The refusal must be a refusal: the transaction rolled back everywhere, so no
# node took half of it. n1 originated it, so n1 is where a partial commit shows.
check "the refused write left no trace on the origin" "base" \
	"$(q n1 "select doc->>'k' from jm_x where id=1")"
# ...and the disjoint write from (a) is still there - a refusal that took the
# document with it would trade one lost key for the rest.
check "the disjoint write survived the refusal" "1" \
	"$(q n1 "select doc->>'other' from jm_x where id=1")"

summary
